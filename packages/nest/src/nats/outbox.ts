/** Default table of the transactional outbox (resolved through `search_path`, i.e. the service schema). */
export const OUTBOX_TABLE = 'outbox';

/** Unquoted last part of a table name, for index names. */
function bareName(table: string): string {
  return table.split('.').at(-1) ?? table;
}

/** Indexes of the outbox table (idempotent), shared by the create and upgrade DDL. */
function outboxIndexSql(table: string): string[] {
  const name = quoteTableName(table);
  const bare = bareName(table);
  const pending = 'published_at IS NULL AND failed_at IS NULL';
  return [
    // Serial relays and the oldest-pending gauge.
    `CREATE INDEX IF NOT EXISTS "${bare}_pending_idx" ON ${name} (created_at, id)`,
    `  WHERE ${pending};`,
    // Per-key relays: claim in commit order, find a key's older rows.
    `CREATE INDEX IF NOT EXISTS "${bare}_pending_seq_idx" ON ${name} (seq)`,
    `  WHERE ${pending};`,
    `CREATE INDEX IF NOT EXISTS "${bare}_pending_key_idx" ON ${name} (entity_key, seq)`,
    `  WHERE ${pending};`,
    // Rows waiting for a retry (few): their keys wait too.
    `CREATE INDEX IF NOT EXISTS "${bare}_retry_idx" ON ${name} (entity_key, seq)`,
    `  WHERE ${pending} AND next_attempt_at IS NOT NULL;`,
    // Parked rows (aisits_outbox_failed_rows).
    `CREATE INDEX IF NOT EXISTS "${bare}_failed_idx" ON ${name} (failed_at)`,
    '  WHERE failed_at IS NOT NULL;',
  ];
}

/**
 * The DDL of the outbox table, for a service migration
 * (`migrations/NNNN_outbox.sql`). `id` is the envelope id (`Nats-Msg-Id`),
 * stable across relay retries; `seq` is the insertion (commit) order the
 * relay publishes each entity key in; `next_attempt_at` is the retry time of
 * a row whose publication failed (`NULL`: due now). Tables created by kit
 * 0.2 lack `seq` and `next_attempt_at`: add them with
 * {@link outboxUpgradeSql}.
 */
export function outboxTableSql(table: string = OUTBOX_TABLE): string {
  const name = quoteTableName(table);
  return [
    `CREATE TABLE IF NOT EXISTS ${name} (`,
    '  id uuid PRIMARY KEY,',
    '  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,',
    '  type text NOT NULL,',
    '  entity_key text,',
    '  data jsonb NOT NULL,',
    '  created_at timestamptz NOT NULL DEFAULT now(),',
    '  attempts integer NOT NULL DEFAULT 0,',
    '  next_attempt_at timestamptz,',
    '  last_error text,',
    '  published_at timestamptz,',
    '  failed_at timestamptz',
    ');',
    ...outboxIndexSql(table),
    '',
  ].join('\n');
}

/**
 * Idempotent DDL that upgrades an outbox table created by kit 0.2
 * ({@link outboxTableSql} without `seq` and `next_attempt_at`) for the
 * per-key relay, for a service migration: adds `next_attempt_at`, adds
 * `seq` numbering the existing rows in their 0.2 relay order
 * (`created_at, id`, so pending rows keep their order), makes it an
 * identity column continuing after the last row, and creates the indexes.
 * A table that already has the columns (or a newer table) is left as is,
 * apart from missing indexes. The `seq` backfill rewrites every row once
 * and locks the table until the migration commits.
 *
 * @example
 * // migrations/0007_outbox_per_key.sql, generated once:
 * // node -e "import('@darmawanweb/ais-its-nest/nats').then((m) => console.log(m.outboxUpgradeSql()))"
 */
export function outboxUpgradeSql(table: string = OUTBOX_TABLE): string {
  const name = quoteTableName(table);
  const bare = bareName(table);
  // Identifiers are lowercase and validated by quoteTableName: no quotes inside.
  const literal = `'${name}'`;
  return [
    `ALTER TABLE ${name} ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz;`,
    'DO $outbox_upgrade$',
    'BEGIN',
    '  IF NOT EXISTS (',
    `    SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass(${literal})`,
    "      AND attname = 'seq' AND attnum > 0 AND NOT attisdropped",
    '  ) THEN',
    `    ALTER TABLE ${name} ADD COLUMN seq bigint;`,
    `    UPDATE ${name} AS o SET seq = r.rn`,
    `      FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM ${name}) AS r`,
    '     WHERE o.id = r.id;',
    `    ALTER TABLE ${name} ALTER COLUMN seq SET NOT NULL;`,
    `    ALTER TABLE ${name} ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;`,
    `    PERFORM setval(pg_get_serial_sequence(${literal}, 'seq'),`,
    `      (SELECT coalesce(max(seq), 0) + 1 FROM ${name}), false);`,
    `    ALTER TABLE ${name} ADD CONSTRAINT "${bare}_seq_key" UNIQUE (seq);`,
    '  END IF;',
    'END',
    '$outbox_upgrade$;',
    ...outboxIndexSql(table),
    '',
  ].join('\n');
}

/** Anything `pg` can query: the pool or the client of an open transaction. */
export type OutboxQueryable = Pick<Pool | PoolClient, 'query'>;

/** Options of {@link enqueueEvent}. */
export interface EnqueueEventOptions {
  /** Envelope id; default a new UUID v7. */
  readonly id?: string | undefined;
  /** Envelope `subject` (entity key); default derived from the payload. */
  readonly entityKey?: string | undefined;
  /** Outbox table. Default {@link OUTBOX_TABLE}. */
  readonly table?: string | undefined;
  /**
   * Largest NATS message the event may become, bytes, typically
   * `NatsClient.maxPayloadBytes()`: a larger event throws
   * {@link EventTooLargeError} before anything is written, instead of being
   * parked by the relay later. The size is the encoded envelope plus a
   * 1 KiB header allowance (`eventMessageSize`). Default: no check.
   */
  readonly maxBytes?: number | undefined;
}

/**
 * Adds an event to the transactional outbox inside the caller's
 * transaction (spec §13.3, §13.6): the row commits or rolls back with the
 * business change, and {@link OutboxRelay} publishes it afterwards, in
 * insertion order per entity key, with the row id as envelope id. Writers
 * that change the same entity concurrently must serialize (e.g. lock the
 * entity row first), so the insertion order of its rows is their commit
 * order.
 *
 * @returns the envelope id.
 * @throws {InvalidEventError} when `data` violates the contract (nothing is written).
 * @throws {EventTooLargeError} when the event exceeds `maxBytes` (nothing is written).
 * @example
 * await withTransaction(this.pool, async (client) => {
 *   await this.vessels.update(client, id, changes);
 *   await enqueueEvent(client, EVENT_TYPES.FLEET_VESSEL_UPSERTED, snapshot, {
 *     maxBytes: this.nats.maxPayloadBytes(),
 *   });
 * });
 */
export async function enqueueEvent<Type extends EventType>(
  client: OutboxQueryable,
  type: Type,
  data: EventPayload<Type>,
  options: EnqueueEventOptions = {},
): Promise<string> {
  // Validates the payload and derives the default entity key.
  const envelope = makeEnvelope({
    type,
    source: 'outbox',
    data,
    id: options.id,
    subject: options.entityKey,
  });
  if (options.maxBytes !== undefined) {
    const sizeBytes = envelopeMessageSize(
      envelope as Parameters<typeof envelopeMessageSize>[0],
    );
    if (sizeBytes > options.maxBytes)
      throw new EventTooLargeError(type, sizeBytes, options.maxBytes);
  }
  await client.query(
    `INSERT INTO ${quoteTableName(options.table ?? OUTBOX_TABLE)} (id, type, entity_key, data, created_at) ` +
      'VALUES ($1, $2, $3, $4::jsonb, $5)',
    [
      envelope.id,
      type,
      envelope.subject ?? null,
      JSON.stringify(envelope.data),
      new Date(envelope.time),
    ],
  );
  return envelope.id;
}

/**
 * How the relay publishes:
 *
 * - `'per-key'` — every replica relays; each pass claims due rows with
 *   `FOR UPDATE SKIP LOCKED` and publishes entity keys concurrently, the
 *   rows of one key in `seq` order. A failed row waits for its retry
 *   (`next_attempt_at`, exponential backoff with jitter) and holds back
 *   only its own key. Needs the `seq` and `next_attempt_at` columns.
 * - `'serial'` — the kit 0.2 relay: one replica at a time (advisory
 *   lock), all rows in order, a pass stops at the first failure and the
 *   relay backs off as a whole.
 */
export type OutboxRelayMode = 'per-key' | 'serial';

