/**
 * Errors that will never succeed for a row: it is parked (`failed_at`)
 * instead of blocking its key (an invalid payload, a subject mismatch, a
 * message larger than the server's `max_payload`).
 */
function isPermanent(error: unknown): boolean {
  return (
    error instanceof InvalidEventError ||
    error instanceof EventSubjectMismatchError ||
    error instanceof EventTooLargeError ||
    isMaxPayloadError(error)
  );
}

/** Signed 64-bit advisory lock key of an outbox table. */
function lockKey(table: string): string {
  return createHash('sha256')
    .update(`aisits:outbox:${table}`)
    .digest()
    .readBigInt64BE(0)
    .toString();
}

/** Result of one relay pass. */
export interface OutboxRelayResult {
  /** Rows published. */
  readonly published: number;
  /**
   * Rows parked (`failed_at`): payload no longer valid, larger than the
   * server's `max_payload`, or `maxAttempts` reached.
   */
  readonly rejected: number;
  /**
   * `true` when the pass did not run: another instance held the relay lock
   * (serial mode), or a serial relay of an older kit holds it (per-key).
   */
  readonly skipped: boolean;
  /** At least one publication failed (retried later, order kept). */
  readonly failed: boolean;
  /** Rows whose publication failed in this pass and that wait for a retry. */
  readonly retrying: number;
  /**
   * Claimed rows left to a later pass because an older row of their entity
   * key was claimed by another relay (per-key mode; `0` in serial mode).
   */
  readonly deferred: number;
  /** Mode the pass ran in. */
  readonly mode: OutboxRelayMode;
}

/** A pass result plus what the loop needs. */
