function positiveInteger(
  value: number | undefined,
  fallback: number,
  name: string,
): number {
  if (value === undefined) return fallback;
  if (!Number.isInteger(value) || value < 1)
    throw new OutboxConfigError(
      `OutboxModule option ${name} must be a positive integer, got ${String(value)}`,
    );
  return value;
}

function positiveNumber(
  value: number | undefined,
  fallback: number,
  name: string,
): number {
  if (value === undefined) return fallback;
  if (!Number.isFinite(value) || value <= 0)
    throw new OutboxConfigError(
      `OutboxModule option ${name} must be a positive number, got ${String(value)}`,
    );
  return value;
}

/** Normalized {@link OutboxModuleOptions}. */
interface OutboxSettings {
  readonly table: string;
  readonly pollIntervalMs: number;
  readonly batchSize: number;
  readonly retentionMs: number;
  readonly autoStart: boolean;
  readonly mode: OutboxRelayMode | undefined;
  readonly publishConcurrency: number;
  readonly retry: { readonly baseMs: number; readonly maxMs: number };
  readonly maxAttempts: number | undefined;
}

function outboxSettings(options: OutboxModuleOptions): OutboxSettings {
  // Options may come from untyped configuration (forRootAsync).
  const mode: unknown = options.mode;
  if (mode !== undefined && mode !== 'per-key' && mode !== 'serial')
    throw new OutboxConfigError(
      `OutboxModule option mode must be 'per-key' or 'serial', got ${JSON.stringify(mode)}`,
    );
  const baseMs = positiveNumber(
    options.retry?.baseMs,
    DEFAULT_OUTBOX_RETRY_BASE_MS,
    'retry.baseMs',
  );
  const maxMs = positiveNumber(
    options.retry?.maxMs,
    DEFAULT_OUTBOX_RETRY_MAX_MS,
    'retry.maxMs',
  );
  return {
    table: options.table ?? OUTBOX_TABLE,
    pollIntervalMs: positiveNumber(
      options.pollIntervalMs,
      DEFAULT_POLL_INTERVAL_MS,
      'pollIntervalMs',
    ),
    batchSize: positiveInteger(
      options.batchSize,
      DEFAULT_BATCH_SIZE,
      'batchSize',
    ),
    retentionMs: positiveNumber(
      options.retentionMs,
      24 * 3_600_000,
      'retentionMs',
    ),
    autoStart: options.autoStart !== false,
    mode: options.mode,
    publishConcurrency: positiveInteger(
      options.publishConcurrency,
      DEFAULT_PUBLISH_CONCURRENCY,
      'publishConcurrency',
    ),
    retry: { baseMs, maxMs: Math.max(baseMs, maxMs) },
    maxAttempts:
      options.maxAttempts === undefined
        ? undefined
        : positiveInteger(options.maxAttempts, 1, 'maxAttempts'),
  };
}

/** What the relay found about its table. */
interface TableShape {
  readonly mode: OutboxRelayMode;
  /** The table has `seq` (serial relays then order by it). */
  readonly hasSeq: boolean;
}

/**
 * Publishes the outbox (spec §13.3, §13.6). In `per-key` mode (tables with
 * `seq` and `next_attempt_at`, see {@link outboxTableSql} and
 * {@link outboxUpgradeSql}) every replica relays: a pass claims up to
 * `batchSize` due rows (`FOR UPDATE SKIP LOCKED`, `seq` order), keeps per
 * entity key the run that starts at the key's oldest pending row, publishes
 * up to `publishConcurrency` keys at once (rows of one key one after the
 * other) and marks the published rows. A failed row gets `attempts + 1`, a
 * sanitized `last_error` and a `next_attempt_at` with exponential backoff
 * and jitter; only its key waits. Rows without an entity key are unordered.
 * In `serial` mode (kit 0.2 tables) one instance at a time publishes in
 * order and a pass stops at the first failure.
 *
 * In both modes, rows that can never be published are parked (`failed_at`)
 * and their key continues: a payload that no longer validates, a subject
 * mismatch, a message larger than the server's `max_payload`, or
 * `maxAttempts` failed attempts. Published rows are deleted after
 * `retentionMs`. Metrics: `aisits_outbox_relayed_total{type,outcome}`,
 * `aisits_outbox_pending`, `aisits_outbox_oldest_pending_seconds`,
 * `aisits_outbox_retrying_rows` (pending rows that failed at least once)
 * and `aisits_outbox_failed_rows` (parked rows).
 */
@Injectable()
export class OutboxRelay
  implements OnApplicationBootstrap, BeforeApplicationShutdown
{
  private readonly logger = new Logger('Outbox');
  private readonly settings: OutboxSettings;
  private readonly table: string;
  private readonly key: string;
  private readonly relayed: Counter<'type' | 'outcome'>;
  private readonly pending: Gauge;
  private readonly oldest: Gauge;
  private readonly retryingRows: Gauge;
  private readonly failedRows: Gauge;
  private loop: Promise<void> | undefined;
  private readonly stop = new AbortController();
  private wake: (() => void) | undefined;
  private lastCleanup = 0;
  private lastGaugeRefresh = Number.NEGATIVE_INFINITY;
  private lastFailedCount = Number.NEGATIVE_INFINITY;
  private shape: Promise<TableShape> | undefined;

  constructor(
    @Inject(PG_POOL) private readonly pool: Pool,
    private readonly publisher: EventPublisher,
    @Inject(OUTBOX_OPTIONS) options: OutboxModuleOptions,
    @Optional() @Inject(MetricsService) metrics: MetricsService | null = null,
  ) {
    this.settings = outboxSettings(options);
    this.table = quoteTableName(this.settings.table);
    this.key = lockKey(this.settings.table);
    const registry = metrics ?? new MetricsService();
    this.relayed = registry.counter({
      name: 'outbox_relayed_total',
      help: 'Outbox rows relayed by event type and outcome (published, failed = retried later, rejected = parked).',
      labelNames: ['type', 'outcome'],
    });
    this.pending = registry.gauge({
      name: 'outbox_pending',
      help: 'Outbox rows waiting to be published.',
    });
    this.oldest = registry.gauge({
      name: 'outbox_oldest_pending_seconds',
      help: 'Age of the oldest outbox row waiting to be published, seconds.',
    });
    this.retryingRows = registry.gauge({
      name: 'outbox_retrying_rows',
      help: 'Outbox rows waiting to be published whose publication failed at least once.',
    });
    this.failedRows = registry.gauge({
      name: 'outbox_failed_rows',
      help: 'Outbox rows parked because they can never be published (failed_at set); an operator must look at them.',
    });
  }

  /**
   * Resolves the relay mode and starts the relay loop (after migrations,
   * which run in `onModuleInit`).
   *
   * @throws {OutboxConfigError} for `mode: 'per-key'` on a table without
   *   the `seq` and `next_attempt_at` columns.
   */
  async onApplicationBootstrap(): Promise<void> {
    if (!this.settings.autoStart) return;
    try {
      await this.mode();
    } catch (error) {
      if (error instanceof OutboxConfigError) throw error;
      // The loop retries (e.g. the table is created by a later migration).
      this.logger.error(
        `Inspecting outbox table ${this.table} failed: ${errorMessage(error)}`,
      );
    }
    this.loop = this.run();
  }

  /** Stops the loop after the current pass. */
  async beforeApplicationShutdown(): Promise<void> {
    this.stop.abort();
    this.wake?.();
    await this.loop?.catch(() => undefined);
  }

  /** Wakes the relay now (e.g. right after committing an enqueue) instead of at the next poll. */
  notify(): void {
    this.wake?.();
  }

  /**
   * The mode the relay runs in: {@link OutboxModuleOptions.mode}, or
   * detected from the table's columns (cached once the table was found).
   *
   * @throws {OutboxConfigError} for `mode: 'per-key'` on a table without
   *   the `seq` and `next_attempt_at` columns.
   */
  async mode(): Promise<OutboxRelayMode> {
    return (await this.tableShape()).mode;
  }

  /**
   * Runs one pass (see the class description); never throws for
   * publication failures. Gauges are refreshed after the pass.
   */
  async relayOnce(): Promise<OutboxRelayResult> {
    const result = await this.pass(true);
    return {
      published: result.published,
      rejected: result.rejected,
      skipped: result.skipped,
      failed: result.failed,
      retrying: result.retrying,
      deferred: result.deferred,
      mode: result.mode,
    };
  }

  /** Deletes rows published longer than `retentionMs` ago; returns how many. */
  async cleanup(): Promise<number> {
    const result = await this.pool.query(
      `DELETE FROM ${this.table} WHERE published_at < $1`,
      [new Date(Date.now() - this.settings.retentionMs)],
    );
    return result.rowCount ?? 0;
  }

  private tableShape(): Promise<TableShape> {
    this.shape ??= this.inspectTable().catch((error: unknown) => {
      // Not cached: the next pass inspects again.
      this.shape = undefined;
      throw error;
    });
    return this.shape;
  }

  private async inspectTable(): Promise<TableShape> {
    const { rows } = await this.pool.query<{
      exists: boolean;
      seq: boolean;
      next_attempt_at: boolean;
    }>(
      `SELECT to_regclass($1) IS NOT NULL AS exists,
              EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass($1)
                       AND attname = 'seq' AND attnum > 0 AND NOT attisdropped) AS seq,
              EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass($1)
                       AND attname = 'next_attempt_at' AND attnum > 0 AND NOT attisdropped) AS next_attempt_at`,
      [this.table],
    );
    const row = rows[0];
    if (row?.exists !== true)
      throw new Error(
        `Outbox table ${this.table} does not exist: create it with outboxTableSql() in a migration`,
      );
    const perKeyReady = row.seq && row.next_attempt_at;
    const requested = this.settings.mode;
    if (requested === 'per-key' && !perKeyReady)
      throw new OutboxConfigError(
        `Outbox table ${this.table} lacks the seq and next_attempt_at columns of mode 'per-key': ` +
          `add them with outboxUpgradeSql('${this.settings.table}') in a migration`,
      );
    const mode = requested ?? (perKeyReady ? 'per-key' : 'serial');
    if (requested === undefined && mode === 'serial') {
      this.logger.warn(
        `Outbox table ${this.table} has no seq/next_attempt_at columns: relaying in serial mode ` +
          '(one replica at a time, a pass stops at the first failure). Add them with ' +
          `outboxUpgradeSql('${this.settings.table}') in a migration to relay per entity key on every replica`,
      );
    } else {
      this.logger.log(`Relaying outbox table ${this.table} in ${mode} mode`);
    }
    return { mode, hasSeq: row.seq };
  }

  private async pass(forceGauges: boolean): Promise<PassResult> {
    const shape = await this.tableShape();
    const result =
      shape.mode === 'per-key'
        ? await this.perKeyPass()
        : await this.serialPass(shape);
    if (!result.skipped) await this.refreshGauges(forceGauges, result);
    return result;
  }

  /** A per-key pass (see the class description). */
  private perKeyPass(): Promise<PassResult> {
    return withTransaction(this.pool, async (client) => {
      // Shared with the other per-key relays, exclusive with serial relays
      // of an older kit (rolling upgrade): they never publish concurrently.
      const locked = await client.query<{ locked: boolean }>(
        'SELECT pg_try_advisory_xact_lock_shared($1::bigint) AS locked',
        [this.key],
      );
      if (locked.rows[0]?.locked !== true) return skippedPass('per-key');
      const t = this.table;
      // Due rows not locked by another relay, oldest first, without rows
      // behind an older row of their key that waits for its retry; each
      // with the seq of its key's previous pending row (the planner keeps
      // only runs that start at the key's oldest pending row).
      const { rows } = await client.query<
        Omit<ClaimedRow, 'entityKey' | 'previousSeq'> & {
          readonly previous_seq: string | null;
        }
      >(
        `SELECT o.id, o.seq::text AS seq, o.type, o.entity_key, o.data, o.created_at, o.attempts,
                (SELECT p.seq::text FROM ${t} p
                  WHERE p.entity_key = o.entity_key AND p.seq < o.seq
                    AND p.published_at IS NULL AND p.failed_at IS NULL
                  ORDER BY p.seq DESC LIMIT 1) AS previous_seq
           FROM ${t} o
          WHERE o.published_at IS NULL AND o.failed_at IS NULL
            AND (o.next_attempt_at IS NULL OR o.next_attempt_at <= now())
            AND NOT EXISTS (
                  SELECT 1 FROM ${t} w
                   WHERE w.entity_key = o.entity_key AND w.seq < o.seq
                     AND w.published_at IS NULL AND w.failed_at IS NULL
                     AND w.next_attempt_at IS NOT NULL AND w.next_attempt_at > now())
          ORDER BY o.seq
          LIMIT $1
          FOR UPDATE OF o SKIP LOCKED`,
        [this.settings.batchSize],
      );
      const claimed: ClaimedRow[] = rows.map((row) => ({
        ...row,
        entityKey: row.entity_key,
        previousSeq: row.previous_seq,
      }));
      const plan = planOutboxRuns(claimed);
      const published: string[] = [];
      const parked: { id: string; error: string }[] = [];
      const retries: { id: string; error: string; delayMs: number }[] = [];
      const slots = new Semaphore(this.settings.publishConcurrency);
      await Promise.all(
        plan.runs.map(async (run) => {
          await slots.acquire();
          try {
            for (const row of run.rows) {
              const outcome = await this.publishRow(row);
              if (outcome.kind === 'published') {
                published.push(row.id);
                continue;
              }
              if (outcome.kind === 'parked') {
                parked.push({ id: row.id, error: outcome.error });
                continue;
              }
              // The key waits for the retry; its later rows stay pending.
              retries.push({
                id: row.id,
                error: outcome.error,
                delayMs: outcome.delayMs,
              });
              break;
            }
          } finally {
            slots.release();
          }
        }),
      );
      await this.markPublished(client, published);
      await this.markParked(client, parked);
      if (retries.length > 0) {
        await client.query(
          `UPDATE ${t} AS o SET attempts = o.attempts + 1, last_error = f.error,
                  next_attempt_at = clock_timestamp() + f.delay_ms * interval '1 millisecond'
             FROM unnest($1::uuid[], $2::text[], $3::double precision[]) AS f(id, error, delay_ms)
            WHERE o.id = f.id`,
          [
            retries.map((retry) => retry.id),
            retries.map((retry) => retry.error),
            retries.map((retry) => retry.delayMs),
          ],
        );
        const first = retries[0];
        this.logger.warn(
          `Publishing ${retries.length} outbox row(s) failed, their entity keys wait for a retry ` +
            `(first in ${first?.delayMs ?? 0} ms): ${first?.error ?? ''}`,
        );
      }
      return {
        published: published.length,
        rejected: parked.length,
        skipped: false,
        failed: retries.length > 0,
        retrying: retries.length,
        deferred: plan.deferred.length,
        mode: 'per-key',
        claimed: claimed.length,
      };
    });
  }

  /** A serial pass: the kit 0.2 relay, parking permanent failures. */
  private serialPass(shape: TableShape): Promise<PassResult> {
    return withTransaction(this.pool, async (client) => {
      const locked = await client.query<{ locked: boolean }>(
        'SELECT pg_try_advisory_xact_lock($1::bigint) AS locked',
        [this.key],
      );
      if (locked.rows[0]?.locked !== true) return skippedPass('serial');
      const { rows } = await client.query<OutboxRow>(
        `SELECT id, type, entity_key, data, created_at, attempts FROM ${this.table} ` +
          'WHERE published_at IS NULL AND failed_at IS NULL ' +
          `ORDER BY ${shape.hasSeq ? 'seq' : 'created_at, id'} LIMIT $1`,
        [this.settings.batchSize],
      );
      const published: string[] = [];
      const parked: { id: string; error: string }[] = [];
      let failed = false;
      for (const row of rows) {
        const outcome = await this.publishRow(row);
        if (outcome.kind === 'published') {
          published.push(row.id);
          continue;
        }
        if (outcome.kind === 'parked') {
          parked.push({ id: row.id, error: outcome.error });
          continue;
        }
        failed = true;
        this.logger.warn(
          `Publishing outbox row ${row.id} (${row.type}) failed, retrying: ${outcome.error}`,
        );
        await client.query(
          `UPDATE ${this.table} SET attempts = attempts + 1, last_error = $2 WHERE id = $1`,
          [row.id, outcome.error],
        );
        break;
      }
      await this.markPublished(client, published);
      await this.markParked(client, parked);
      return {
        published: published.length,
        rejected: parked.length,
        skipped: false,
        failed,
        retrying: failed ? 1 : 0,
        deferred: 0,
        mode: 'serial',
        claimed: rows.length,
      };
    });
  }

  /** Publishes one row and classifies the outcome (counted in `aisits_outbox_relayed_total`). */
  private async publishRow(row: OutboxRow): Promise<RowOutcome> {
    try {
      await this.publisher.publishEvent(
        row.type,
        // Stored by enqueueEvent from a validated payload; validated again on publish.
        row.data as EventPayload<EventType>,
        {
          id: row.id,
          time: row.created_at,
          entityKey: row.entity_key ?? undefined,
        },
      );
      this.relayed.inc({ type: row.type, outcome: 'published' });
      return { kind: 'published' };
    } catch (error) {
      const attempts = row.attempts + 1;
      const message = sanitizeOutboxError(error);
      const { maxAttempts } = this.settings;
      if (isPermanent(error)) {
        this.relayed.inc({ type: row.type, outcome: 'rejected' });
        this.logger.error(
          `Outbox row ${row.id} (${row.type}) can never be published, parked (failed_at): ${message}`,
        );
        return { kind: 'parked', error: message };
      }
      if (maxAttempts !== undefined && attempts >= maxAttempts) {
        this.relayed.inc({ type: row.type, outcome: 'rejected' });
        this.logger.error(
          `Outbox row ${row.id} (${row.type}) failed ${attempts} time(s), parked (failed_at): ${message}`,
        );
        return {
          kind: 'parked',
          error: sanitizeOutboxError(
            `gave up after ${attempts} attempts: ${message}`,
          ),
        };
      }
      this.relayed.inc({ type: row.type, outcome: 'failed' });
      return {
        kind: 'retry',
        error: message,
        delayMs: outboxRetryDelayMs(attempts, this.settings.retry),
      };
    }
  }

  private async markPublished(
    client: PoolClient,
    ids: readonly string[],
  ): Promise<void> {
    if (ids.length === 0) return;
    await client.query(
      `UPDATE ${this.table} SET published_at = now() WHERE id = ANY($1::uuid[])`,
      [ids],
    );
  }

  private async markParked(
    client: PoolClient,
    rows: readonly { readonly id: string; readonly error: string }[],
  ): Promise<void> {
    if (rows.length === 0) return;
    await client.query(
      `UPDATE ${this.table} AS o SET attempts = o.attempts + 1, last_error = f.error, failed_at = now()
         FROM unnest($1::uuid[], $2::text[]) AS f(id, error)
        WHERE o.id = f.id`,
      [rows.map((row) => row.id), rows.map((row) => row.error)],
    );
  }

  /**
   * Refreshes the gauges from the committed table: always after an explicit
   * {@link relayOnce}, at most every second from the loop; parked rows are
   * counted at most every 10 s unless the pass parked some.
   */
  private async refreshGauges(
    force: boolean,
    result: OutboxRelayResult,
  ): Promise<void> {
    const now = Date.now();
    if (!force && now - this.lastGaugeRefresh < GAUGE_REFRESH_INTERVAL_MS)
      return;
    this.lastGaugeRefresh = now;
    try {
      const { rows } = await this.pool.query<{
        pending: string;
        retrying: string;
        oldest: Date | null;
      }>(
        `SELECT count(*) AS pending, count(*) FILTER (WHERE attempts > 0) AS retrying,
                min(created_at) AS oldest
           FROM ${this.table} WHERE published_at IS NULL AND failed_at IS NULL`,
      );
      const row = rows[0];
      this.pending.set(Number(row?.pending ?? 0));
      this.retryingRows.set(Number(row?.retrying ?? 0));
      this.oldest.set(
        row?.oldest === undefined || row.oldest === null
          ? 0
          : Math.max(0, (now - row.oldest.getTime()) / 1000),
      );
      if (
        force ||
        result.rejected > 0 ||
        now - this.lastFailedCount >= FAILED_COUNT_INTERVAL_MS
      ) {
        this.lastFailedCount = now;
        const failed = await this.pool.query<{ failed: string }>(
          `SELECT count(*) AS failed FROM ${this.table} WHERE failed_at IS NOT NULL AND published_at IS NULL`,
        );
        this.failedRows.set(Number(failed.rows[0]?.failed ?? 0));
      }
    } catch (error) {
      this.logger.debug(
        `Refreshing the outbox gauges failed: ${errorMessage(error)}`,
      );
    }
  }

  /** Read through a method: the signal changes while the loop awaits. */
  private isStopping(): boolean {
    return this.stop.signal.aborted;
  }

  private async run(): Promise<void> {
    const pollMs = this.settings.pollIntervalMs;
    let backoffMs = pollMs;
    while (!this.isStopping()) {
      let busy = false;
      try {
        const result = await this.pass(false);
        const progress = result.published + result.rejected;
        busy =
          result.mode === 'per-key'
            ? result.claimed >= this.settings.batchSize && progress > 0
            : progress >= this.settings.batchSize;
        // Per-key failures wait per row (next_attempt_at); serial ones
        // back off the whole relay, as in kit 0.2.
        backoffMs =
          result.mode === 'serial' && result.failed
            ? Math.min(backoffMs * 2, MAX_LOOP_BACKOFF_MS)
            : pollMs;
        if (Date.now() - this.lastCleanup > 10 * 60_000) {
          this.lastCleanup = Date.now();
          await this.cleanup();
        }
      } catch (error) {
        backoffMs = Math.min(backoffMs * 2, MAX_LOOP_BACKOFF_MS);
        this.logger.error(`Outbox relay pass failed: ${errorMessage(error)}`);
      }
      if (busy || this.isStopping()) continue;
      await new Promise<void>((resolve) => {
        this.wake = resolve;
        void sleep(backoffMs, undefined, {
          signal: this.stop.signal,
          ref: false,
        })
          .catch(() => undefined)
          .then(resolve);
      });
      this.wake = undefined;
    }
  }
}

function skippedPass(mode: OutboxRelayMode): PassResult {
  return {
    published: 0,
    rejected: 0,
    skipped: true,
    failed: false,
    retrying: 0,
    deferred: 0,
    mode,
    claimed: 0,
  };
}

/**
 * The transactional outbox relay (requires `DatabaseModule` and
 * `NatsModule`; list the target streams in `NatsModule.forRoot({ streams })`).
 * Create the table with {@link outboxTableSql} in a migration (upgrade a
 * kit 0.2 table with {@link outboxUpgradeSql}) and add rows with
 * {@link enqueueEvent} inside your transactions.
 *
 * @example
 * OutboxModule.forRootAsync({
 *   inject: [APP_CONFIG],
 *   useFactory: (config: Config) => ({ batchSize: config.OUTBOX_BATCH_SIZE }),
 * })
 */
@Module({})
export class OutboxModule {
  /** Registers the relay with static options. */
  static forRoot(options: OutboxModuleOptions = {}): DynamicModule {
    return {
      module: OutboxModule,
      providers: [{ provide: OUTBOX_OPTIONS, useValue: options }, OutboxRelay],
      exports: [OutboxRelay],
    };
  }

  /**
   * Like {@link forRoot}, with the options built by a factory (e.g. from
   * the typed configuration, `inject: [APP_CONFIG]`).
   */
  static forRootAsync(options: OutboxModuleAsyncOptions): DynamicModule {
    return {
      module: OutboxModule,
      imports: [...(options.imports ?? [])],
      providers: [
        {
          provide: OUTBOX_OPTIONS,
          useFactory: options.useFactory,
          inject: [...(options.inject ?? [])],
        },
        OutboxRelay,
      ],
      exports: [OutboxRelay],
    };
  }
}
