/** A valid envelope of `type` carrying its example payload. */
export function exampleEnvelope(
  type: EventType,
  source = 'fleet',
): AnyEventEnvelope {
  // `type` and the example payload correspond by construction of EVENT_EXAMPLES.
  return makeEnvelope({
    type,
    source,
    data: EVENT_EXAMPLES[type],
  }) as AnyEventEnvelope;
}
