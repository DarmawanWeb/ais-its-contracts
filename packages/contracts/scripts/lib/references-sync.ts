import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import type { FieldError } from '../../src/api/problem.js';
import {
  type MethodologyCatalog,
  validateCatalog,
} from '../../src/references/catalog.js';
import { prettify } from './format.js';

/** Files of the catalog in `docs/references` of the central repository. */
export const CATALOG_FILES = {
  references: 'references.json',
  methods: 'methods.json',
} as const;

/** Directory of the generated data modules, relative to the package. */
export const DATA_MODULE_DIR = 'src/references/data';

/** Generated data module of each catalog collection. */
const DATA_MODULES = {
  references: {
    file: 'references.ts',
    constant: 'REFERENCES',
    type: 'Reference',
    summary: 'References (sources) of the methodology catalog',
  },
  methods: {
    file: 'methods.ts',
    constant: 'METHODS',
    type: 'Method',
    summary:
      'Methods (formulas, constants, thresholds and rules) of the methodology catalog',
  },
} as const;

type Collection = keyof typeof DATA_MODULES;

const COLLECTIONS: readonly Collection[] = ['references', 'methods'];

/**
 * Source text of the data modules of a validated catalog, keyed by path
 * relative to the package (formatted with Prettier).
 */
export async function renderDataModules(
  catalog: MethodologyCatalog,
  packageDir: string,
): Promise<Map<string, string>> {
  const modules = new Map<string, string>();
  for (const collection of COLLECTIONS) {
    const module = DATA_MODULES[collection];
    const relativePath = path.posix.join(DATA_MODULE_DIR, module.file);
    const source = [
      `// Generated by \`pnpm run references:sync\` from docs/references/${CATALOG_FILES[collection]}. Do not edit.`,
      `import type { ${module.type} } from '../schemas.js';`,
      '',
      `/** ${module.summary} (spec 17), validated by \`references:sync\`. */`,
      `export const ${module.constant}: readonly ${module.type}[] = ${JSON.stringify(catalog[collection])};`,
      '',
    ].join('\n');
    modules.set(
      relativePath,
      await prettify(path.join(packageDir, relativePath), source),
    );
  }
  return modules;
}

/** Options of {@link syncReferences}. */
export interface SyncReferencesOptions {
  /** Directory holding `references.json` and `methods.json`. */
  readonly sourceDir: string;
  /** Root of the contracts package (where `src/references/data` lives). */
  readonly packageDir: string;
  /** Compare only; never write. */
  readonly check: boolean;
}

/** Outcome of {@link syncReferences}. */
export type SyncReferencesOutcome =
  | { readonly kind: 'missing'; readonly files: readonly string[] }
  | { readonly kind: 'invalid'; readonly issues: readonly FieldError[] }
  | {
      readonly kind: 'synced' | 'checked';
      /** Data modules that were written (`synced`) or differ (`checked`). */
      readonly changed: readonly string[];
      readonly references: number;
      readonly methods: number;
    };

async function readCatalogFile(
  file: string,
): Promise<{ readonly json: unknown } | { readonly issue: FieldError } | null> {
  let text: string;
  try {
    text = await readFile(file, 'utf8');
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return null;
    }
    throw error;
  }
  try {
    return { json: JSON.parse(text) as unknown };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return {
      issue: {
        field: path.basename(file),
        message: `Invalid JSON: ${reason}`,
      },
    };
  }
}

/**
 * Entries of a catalog file: the file holds the array itself or an object with
 * the array under the collection name (e.g. next to a `$schema` member).
 */
function catalogEntries(json: unknown, collection: Collection): unknown {
  if (
    typeof json === 'object' &&
    json !== null &&
    !Array.isArray(json) &&
    Object.hasOwn(json, collection)
  ) {
    return Reflect.get(json, collection);
  }
  return json;
}

async function readIfExists(file: string): Promise<string | null> {
  try {
    return await readFile(file, 'utf8');
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return null;
    }
    throw error;
  }
}

/**
 * Copies the methodology catalog into the package: reads both JSON files
 * (each an array, or `{ "<collection>": [...] }`),
 * validates them with {@link validateCatalog} (zod schemas, unique ids, no
 * dangling `referenceIds`) and writes the generated data modules. Nothing is
 * written when a file is missing or invalid, or in `check` mode.
 */
export async function syncReferences(
  options: SyncReferencesOptions,
): Promise<SyncReferencesOutcome> {
  const contents = new Map<Collection, unknown>();
  const missing: string[] = [];
  const issues: FieldError[] = [];
  for (const collection of COLLECTIONS) {
    const file = path.join(options.sourceDir, CATALOG_FILES[collection]);
    const result = await readCatalogFile(file);
    if (result === null) missing.push(file);
    else if ('issue' in result) issues.push(result.issue);
    else contents.set(collection, catalogEntries(result.json, collection));
  }
  if (missing.length > 0) return { kind: 'missing', files: missing };
  if (issues.length > 0) return { kind: 'invalid', issues };

  const validation = validateCatalog({
    references: contents.get('references'),
    methods: contents.get('methods'),
  });
  if (!validation.success) {
    return { kind: 'invalid', issues: validation.issues };
  }

  const modules = await renderDataModules(
    validation.catalog,
    options.packageDir,
  );
  const changed: string[] = [];
  for (const [relativePath, content] of modules) {
    const file = path.join(options.packageDir, relativePath);
    if ((await readIfExists(file)) === content) continue;
    changed.push(relativePath);
    if (!options.check) await writeFile(file, content);
  }
  return {
    kind: options.check ? 'checked' : 'synced',
    changed,
    references: validation.catalog.references.length,
    methods: validation.catalog.methods.length,
  };
}
