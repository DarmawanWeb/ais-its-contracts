import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import {
  CATALOG_METHODS,
  CATALOG_REFERENCES,
} from '../../src/references/__fixtures__/catalog.js';
import { validateCatalog } from '../../src/references/catalog.js';
import { METHODS, REFERENCES } from '../../src/references/lookup.js';
import {
  CATALOG_FILES,
  DATA_MODULE_DIR,
  readCatalog,
  renderDataModules,
  syncReferences,
} from './references-sync.js';

const PACKAGE_DIR = path.resolve(
  fileURLToPath(new URL('../..', import.meta.url)),
);

/** Imports a generated module and returns one of its exports. */
async function importExport(file: string, name: string): Promise<unknown> {
  const module: unknown = await import(pathToFileURL(file).href);
  return typeof module === 'object' && module !== null
    ? Reflect.get(module, name)
    : undefined;
}

describe('syncReferences', () => {
  let workDir: string;
  let sourceDir: string;
  let packageDir: string;

  const writeCatalog = async (references: unknown, methods: unknown) => {
    await writeFile(
      path.join(sourceDir, CATALOG_FILES.references),
      JSON.stringify(references),
    );
    await writeFile(
      path.join(sourceDir, CATALOG_FILES.methods),
      JSON.stringify(methods),
    );
  };

  const dataModule = (file: string) =>
    path.join(packageDir, DATA_MODULE_DIR, file);

  beforeEach(async () => {
    workDir = await mkdtemp(path.join(tmpdir(), 'ais-its-references-'));
    sourceDir = path.join(workDir, 'docs', 'references');
    packageDir = path.join(workDir, 'package');
    await mkdir(sourceDir, { recursive: true });
    await mkdir(path.join(packageDir, DATA_MODULE_DIR), { recursive: true });
  });

  afterEach(async () => {
    await rm(workDir, { recursive: true, force: true });
  });

  it('reports missing catalog files without writing anything', async () => {
    const outcome = await syncReferences({
      sourceDir,
      packageDir,
      check: false,
    });
    expect(outcome).toEqual({
      kind: 'missing',
      files: [
        path.join(sourceDir, 'references.json'),
        path.join(sourceDir, 'methods.json'),
      ],
    });
  });

  it('copies a valid catalog into importable, normalized data modules', async () => {
    await writeCatalog(CATALOG_REFERENCES, CATALOG_METHODS);
    const outcome = await syncReferences({
      sourceDir,
      packageDir,
      check: false,
    });
    expect(outcome).toEqual({
      kind: 'synced',
      changed: [
        'src/references/data/references.ts',
        'src/references/data/methods.ts',
      ],
      references: 3,
      methods: 3,
    });

    const expected = validateCatalog({
      references: CATALOG_REFERENCES,
      methods: CATALOG_METHODS,
    });
    expect(expected.success).toBe(true);
    const references = await importExport(
      dataModule('references.ts'),
      'REFERENCES',
    );
    const methods = await importExport(dataModule('methods.ts'), 'METHODS');
    expect(expected.success && { references, methods }).toEqual(
      expected.success && expected.catalog,
    );
    const source = await readFile(dataModule('methods.ts'), 'utf8');
    expect(source).toMatch(/^\/\/ Generated by `pnpm run references:sync`/);
    expect(source).toContain('export const METHODS: readonly Method[] = [');

    expect(
      await syncReferences({ sourceDir, packageDir, check: true }),
    ).toMatchObject({ kind: 'checked', changed: [] });
  });

  it('accepts catalog files that wrap the array next to a $schema', async () => {
    await writeCatalog(
      {
        $schema: '../../schemas/methodology.references.json',
        references: CATALOG_REFERENCES,
      },
      { methods: CATALOG_METHODS },
    );
    expect(
      await syncReferences({ sourceDir, packageDir, check: false }),
    ).toMatchObject({ kind: 'synced', references: 3, methods: 3 });
  });

  it('rejects dangling referenceIds and leaves the data modules untouched', async () => {
    await writeFile(dataModule('methods.ts'), 'untouched');
    await writeCatalog(CATALOG_REFERENCES.slice(1), CATALOG_METHODS);
    const outcome = await syncReferences({
      sourceDir,
      packageDir,
      check: false,
    });
    expect(outcome).toEqual({
      kind: 'invalid',
      issues: [
        expect.objectContaining({
          field: 'methods.0.referenceIds.0',
          code: 'unknown_reference',
        }),
      ],
    });
    expect(await readFile(dataModule('methods.ts'), 'utf8')).toBe('untouched');
  });

  it('reports malformed JSON per file', async () => {
    await writeCatalog([], []);
    await writeFile(path.join(sourceDir, CATALOG_FILES.methods), '[{');
    const outcome = await syncReferences({
      sourceDir,
      packageDir,
      check: false,
    });
    expect(outcome).toMatchObject({
      kind: 'invalid',
      issues: [{ field: 'methods.json' }],
    });
  });

  it('reads and validates the catalog for other tools (references:verify)', async () => {
    expect((await readCatalog(sourceDir)).kind).toBe('missing');
    await writeCatalog(CATALOG_REFERENCES, CATALOG_METHODS);
    const read = await readCatalog(sourceDir);
    const expected = validateCatalog({
      references: CATALOG_REFERENCES,
      methods: CATALOG_METHODS,
    });
    expect(expected.success).toBe(true);
    expect(read).toEqual({
      kind: 'valid',
      catalog: expected.success ? expected.catalog : null,
    });
    await writeCatalog(CATALOG_REFERENCES, [
      { ...CATALOG_METHODS[0], referenceIds: ['no-such-reference'] },
    ]);
    expect((await readCatalog(sourceDir)).kind).toBe('invalid');
  });

  it('detects outdated data modules in check mode without writing', async () => {
    await writeCatalog(CATALOG_REFERENCES, CATALOG_METHODS);
    await writeFile(dataModule('references.ts'), 'stale');
    const outcome = await syncReferences({
      sourceDir,
      packageDir,
      check: true,
    });
    expect(outcome).toMatchObject({
      kind: 'checked',
      changed: [
        'src/references/data/references.ts',
        'src/references/data/methods.ts',
      ],
    });
    expect(await readFile(dataModule('references.ts'), 'utf8')).toBe('stale');
  });
});

describe('committed data modules', () => {
  it('are exactly what references:sync renders for the shipped catalog', async () => {
    const modules = await renderDataModules(
      { references: REFERENCES, methods: METHODS },
      PACKAGE_DIR,
    );
    for (const [relativePath, content] of modules) {
      expect(
        await readFile(path.join(PACKAGE_DIR, relativePath), 'utf8'),
        relativePath,
      ).toBe(content);
    }
  });
});
